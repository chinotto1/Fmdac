"""Write firmware/src/play_fir.h. Host only: the FM-1 image includes the header, not this script.

A two-point blend from 48 kHz down to the headphone clock is a lowpass (about -0.8 dB
at 8 kHz, -3 dB at 16 kHz). This is a windowed sinc, 64 phases of 32 taps, cutoff
0.45 cycles per input sample, Kaiser beta 8.5, Q15, each phase scaled to DC gain 1.
The player blends the two phases around the fraction. Measured on the host against
sines: level within 0.05 dB from 100 Hz through 17 kHz at the 48 kHz ratio.
"""
import numpy as np
from pathlib import Path

TAPS = 32
PHASES = 64
CUTOFF = 0.45
BETA = 8.5


def design():
    h = np.zeros((PHASES, TAPS))
    center = (TAPS - 1) / 2.0
    n = np.arange(TAPS)
    w = np.kaiser(TAPS, BETA)
    for p in range(PHASES):
        delay = p / float(PHASES)
        x = n - (center + delay)
        s = np.ones_like(x)
        nz = np.abs(x) > 1e-15
        s[nz] = np.sin(2 * np.pi * CUTOFF * x[nz]) / (np.pi * x[nz])
        c = s * w
        h[p] = c / np.sum(c)
    q = np.clip(np.round(h * 32768.0), -32768, 32767).astype(np.int64)
    for p in range(PHASES):
        err = 32768 - int(q[p].sum())
        k = int(np.argmax(h[p]))
        q[p, k] = np.clip(q[p, k] + err, -32768, 32767)
    worst = int(np.max(np.sum(np.abs(q), axis=1)))
    # play_dot accumulates in int32. sum(|tap|) * 32767 must fit, with room for the round.
    if worst * 32767 > 2147483647 - 65536:
        raise SystemExit(f"taps do not fit in int32 (abs sum {worst})")
    if not np.all(q.sum(axis=1) == 32768):
        raise SystemExit("DC gain is not 32768")
    return q


def main():
    q = design()
    out = Path(__file__).resolve().parents[1] / "firmware" / "src" / "play_fir.h"
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* generated by tools/gen_play_fir.py: do not edit. Headphone playback filter.",
        " * 64 phases, 32 taps, Kaiser beta 8.5, cutoff 0.45 cycles/sample, Q15.",
        " * Tap 0 is the oldest sample. Each phase sums to 32768. The absolute sum of",
        " * a phase stays under 2.0, so the int32 dot product in play_down.h fits.",
        " * The table is not const and is placed in .data: the headphone interrupt",
        " * reads it on every sample and must not wait on flash. */",
        "#ifndef PLAY_FIR_H",
        "#define PLAY_FIR_H",
        "#define PLAY_FIR_T 32u",
        "#define PLAY_FIR_P 64u",
        "#define PLAY_FIR_SHIFT 10u   /* 65536 / 64 phases */",
        "#define PLAY_FIR_MASK 1023u",
        "static int16_t PLAY_FIR[64][32] __attribute__((section(\".data\"))) = {",
    ]
    for p in range(PHASES):
        row = ", ".join(str(int(v)) for v in q[p])
        lines.append(f"    {{{row}}},")
    lines.append("};")
    lines.append("#endif")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out} abs-sum {int(np.max(np.sum(np.abs(q), axis=1)))}")


if __name__ == "__main__":
    main()

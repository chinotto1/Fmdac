/* Host-only. Writes firmware/src/cast_tab.h. Not linked into the FM-1 image.
 *
 *   cc -O2 -Ifirmware/src -Itools -o build/bake_cast tools/bake_cast.c tools/cast_design.c -lm
 *   ./build/bake_cast > firmware/src/cast_tab.h
 */
#include "cast_design.h"

#include <stdio.h>
#include <stdlib.h>

static const int RATE[5][5] = {
    {44100, 44100, 44100, 44100, 44100},
    {49096, 49096, 49096, 49096, 49096},
    {12000, 18000, 22050, 26040, 32000},
    {14000, 20000, 24000, 27777, 32000},
    {11025, 16000, 22050, 32000, 40000},
};
static const int TONE[5] = {0, 200, 500, 750, 1000};
static const char *NAME[5] = {"VS", "DX7", "SP", "EII", "S950"};

static void die(const char *s) {
  fprintf(stderr, "bake_cast: %s\n", s);
  exit(1);
}

static void coef(const CastBq *b) {
  printf("    {%d, %d, %d, %d, %d}", b->b0, b->b1, b->b2, b->a1, b->a2);
}

static void dump_row(const CastBq *b, int n, int slots) {
  int i;
  printf("  {");
  for (i = 0; i < slots; i++) {
    if (i) printf(", ");
    if (i < n) coef(&b[i]);
    else printf("{0, 0, 0, 0, 0}");
  }
  printf("}");
}

int main(void) {
  CastDac d;
  int m, t, r, i;

  printf("/* SPDX-License-Identifier: GPL-3.0-only */\n");
  printf("/* Generated by tools/bake_cast.c from tools/cast_design.c. Do not edit.\n");
  printf(" * Host sample rate 44100. Tone slots are 0, 200, 500, 750, 1000 milli.\n");
  printf(" * Prophet VS post is 4-pole (2 biquads); 500 milli is the 8 kHz stand-in.\n");
  printf(" * SP-1200 pre is 4-pole at 11070 Hz. Post is off at tone 0 and 500.\n");
  printf(" * Emulator II pre is 2-pole at 12 kHz, post is 4-pole, 500 milli is 12 kHz.\n");
  printf(" * S950 pre and post are 6-pole at min(0.40*rate, 19000). Tone is unused.\n");
  printf(" */\n");
  printf("#ifndef CAST_TAB_H\n#define CAST_TAB_H\n#include <stdint.h>\n\n");
  printf("typedef struct { int32_t b0, b1, b2, a1, a2; } CastCoef;\n\n");
  printf("static const uint16_t CAST_RATE[5][5] = {\n");
  for (m = 0; m < 5; m++) {
    printf("    {");
    for (r = 0; r < 5; r++) printf("%s%d", r ? ", " : "", RATE[m][r]);
    printf("}%s\n", m == 4 ? "" : ",");
  }
  printf("};\n\n");
  printf("static const uint16_t CAST_TONE_MILLI[5] = {0, 200, 500, 750, 1000};\n\n");

  printf("static const CastCoef CAST_VS_POST[5][2] = {\n");
  for (t = 0; t < 5; t++) {
    cast_design(&d, CAST_VS, 12, 44100, TONE[t], 44100);
    if (d.npre != 0 || d.npost != 2) die("VS shape");
    printf("    ");
    dump_row(d.post, d.npost, 2);
    printf("%s\n", t == 4 ? "" : ",");
  }
  printf("};\n\n");

  cast_design(&d, CAST_SP1200, 12, 26040, 0, 44100);
  if (d.npre != 2) die("SP pre");
  printf("static const CastCoef CAST_SP_PRE[2] = ");
  dump_row(d.pre, 2, 2);
  printf(";\n\n");
  printf("static const uint8_t CAST_SP_NPOST[5] = {");
  {
    int npost[5];
    CastDac slot[5];
    for (t = 0; t < 5; t++) {
      cast_design(&slot[t], CAST_SP1200, 12, 26040, TONE[t], 44100);
      if (slot[t].npre != 2 || slot[t].npost > 2) die("SP post");
      npost[t] = slot[t].npost;
      printf("%s%d", t ? ", " : "", npost[t]);
    }
    printf("};\n");
    printf("static const CastCoef CAST_SP_POST[5][2] = {\n");
    for (t = 0; t < 5; t++) {
      printf("    ");
      dump_row(slot[t].post, slot[t].npost, 2);
      printf("%s\n", t == 4 ? "" : ",");
    }
    printf("};\n\n");
  }

  cast_design(&d, CAST_EII, 8, 27777, 500, 44100);
  if (d.npre != 1 || d.npost != 2 || !d.dc_block) die("EII shape");
  printf("static const CastCoef CAST_EII_PRE[1] = ");
  dump_row(d.pre, 1, 1);
  printf(";\n");
  printf("static const CastCoef CAST_EII_POST[5][2] = {\n");
  for (t = 0; t < 5; t++) {
    cast_design(&d, CAST_EII, 8, 27777, TONE[t], 44100);
    if (d.npre != 1 || d.npost != 2) die("EII post");
    printf("    ");
    dump_row(d.post, d.npost, 2);
    printf("%s\n", t == 4 ? "" : ",");
  }
  printf("};\n\n");

  printf("static const CastCoef CAST_S950_PRE[5][3] = {\n");
  for (r = 0; r < 5; r++) {
    cast_design(&d, CAST_S950, 12, RATE[4][r], 500, 44100);
    if (d.npre != 3 || d.npost != 3) die("S950 shape");
    printf("    ");
    dump_row(d.pre, 3, 3);
    printf("%s\n", r == 4 ? "" : ",");
  }
  printf("};\n");
  printf("static const CastCoef CAST_S950_POST[5][3] = {\n");
  for (r = 0; r < 5; r++) {
    cast_design(&d, CAST_S950, 12, RATE[4][r], 500, 44100);
    printf("    ");
    dump_row(d.post, 3, 3);
    printf("%s\n", r == 4 ? "" : ",");
  }
  printf("};\n\n");

  printf("/* steps at 44100, for the ear, not read by the firmware:\n");
  for (m = 0; m < 5; m++) {
    printf(" * %s", NAME[m]);
    for (r = 0; r < 5; r++) {
      unsigned step = ((unsigned)RATE[m][r] << 16) / 44100u;
      printf(" %u", step);
    }
    printf("\n");
  }
  printf(" */\n\n");
  (void)i;
  printf("#endif\n");
  return 0;
}
